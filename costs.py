DIFFICULTY_INDEX = {"easy": 0, "medium": 1, "hard": 2, "impoppable": 3}


def tower_cost(tower_type, difficulty):
    return TOWER_COSTS[tower_type][DIFFICULTY_INDEX[difficulty]]


def upgrade_cost(tower_type, path_index, current_tier, difficulty):
    """current_tier is 0-indexed (monkey.upgrades[path_index]); returns
    cost to go from current_tier -> current_tier + 1."""
    idx = DIFFICULTY_INDEX[difficulty]
    return UPGRADE_COSTS[tower_type][path_index][current_tier][idx]